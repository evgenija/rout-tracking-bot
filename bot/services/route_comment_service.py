def get_route_comment(
    driver_name: str,
    odometer_km: float | None,
    tracking_km: float | None,
) -> str:
    """
    Повертає рандомний коментар відповідно до розбіжності одометр vs трекінг.
    Якщо tracking_km == 0 або будь-яке значення None — повертає порожній рядок.
    odometer_km — пробіг за одометром (фініш - старт), не абсолютне значення.
    """
    if not tracking_km or odometer_km is None:
        return ""

    diff_pct = (odometer_km - tracking_km) / tracking_km

    if diff_pct > 0:
        if diff_pct <= _NORM_THRESHOLD:
            pool = _POOL_NORM
        elif diff_pct < _CRITICAL_THRESHOLD:
            pool = _POOL_CHECK
        else:
            pool = _POOL_CRITICAL
    else:
        abs_diff = abs(diff_pct)
        if abs_diff <= _NORM_THRESHOLD:
            pool = _POOL_NORM
        elif abs_diff < _CRITICAL_THRESHOLD:
            pool = _POOL_GOOD
        else:
            pool = _POOL_WOW

    return random.choice(pool).format(name=driver_name)
